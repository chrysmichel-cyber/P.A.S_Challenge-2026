const test=require('node:test'),assert=require('node:assert');
const {createWorld,cleanChat,cleanAvatar}=require('../server/world.cjs');
const {createServer}=require('../server/server.cjs');
let t=1e6;const W=()=>createWorld({now:()=>t});
const J=(w,n,x)=>w.join(Object.assign({name:n,room:'wolof',consent:true},x||{}));
test('nettoyage du chat : liens, e-mails, téléphones, contrôle',()=>{
 assert.equal(cleanChat('va sur https://evil.com/x ok'),'va sur *** ok');
 assert.equal(cleanChat('écris à bob@mail.com'),'écris à ***');
 assert.equal(cleanChat('appelle +225 07 12 34 56 78'),'appelle ***');
 assert.equal(cleanChat('visite site.com maintenant'),'visite *** maintenant');
 assert.equal(cleanChat('a\u0000b\n\n c  d'),'a b c d');
 assert.equal(cleanChat('x'.repeat(500)).length,200);assert.equal(cleanChat(null),'')});
test('avatar : uniquement des couleurs bornées',()=>{
 assert.deepEqual(cleanAvatar({skin:0xaa8855,top:'<script>',hairCol:-1,fem:true,x:1,hs:'tresses',hat:'<img src=x>',pat:9}),{skin:0xaa8855,fem:true,hs:'tresses'})});
test('join : consentement, pseudo, salon, doublons de pseudo',()=>{const w=W();
 assert.throws(()=>w.join({name:'Kofi',room:'wolof'}),e=>e.code==='consent_required');
 assert.throws(()=>w.join({name:'<b>',room:'wolof',consent:true}),e=>e.code==='bad_name');
 assert.throws(()=>w.join({name:'Kofi',room:'../x',consent:true}),e=>e.code==='bad_room');
 const a=J(w,'Kofi'),b=J(w,'kofi');assert.equal(a.name,'Kofi');assert.notEqual(b.name.toLowerCase(),'kofi');
 assert.equal(a.id.length,10);assert.ok(!('sid' in a.state))});
test('les joueurs d’un même salon se voient, pas ceux d’un autre',()=>{const w=W();
 const a=J(w,'Awa',{x:5,z:6}),b=J(w,'Moussa'),c=w.join({name:'Zola',room:'zoulou',consent:true});
 w.sync(b.sid,{x:10,z:20,h:1,a:1});const v=w.sync(a.sid,{x:5,z:6});
 assert.equal(v.players.length,1);assert.equal(v.players[0].name,'Moussa');assert.equal(v.players[0].x,10);
 assert.equal(w.sync(c.sid,{}).players.length,0)});
test('positions bornées et valeurs invalides ignorées',()=>{const w=W(),a=J(w,'Awa');
 w.sync(a.sid,{x:1e9,z:'abc',h:NaN});const b=J(w,'Bo');const p=w.sync(b.sid,{}).players[0];assert.equal(p.x,200);assert.ok(Number.isFinite(p.z))});
test('chat : curseur, ordre, limite de débit, doublons',()=>{const w=W(),a=J(w,'Awa'),b=J(w,'Bo');
 let v=w.sync(a.sid,{say:'Bonjour !'});assert.ok(!v.chatError);
 const got=w.sync(b.sid,{since:0});assert.ok(got.chat.some(m=>m.text==='Bonjour !'&&m.name==='Awa'));
 const cur=got.cursor;assert.equal(w.sync(b.sid,{since:cur}).chat.length,0);
 v=w.sync(a.sid,{say:'encore'});assert.equal(v.chatError.code,'slow_down');
 t+=2000;v=w.sync(a.sid,{say:'Bonjour !'});assert.equal(v.chatError.code,'duplicate');
 t+=2000;v=w.sync(a.sid,{say:'  '});assert.ok(!v.chatError,'message vide ignoré');
 let n=0;for(let i=0;i<25;i++){t+=1600;const r=w.sync(a.sid,{say:'m'+i});if(r.chatError)n++}assert.ok(n>0,'plafond par minute')});
test('signalements : 3 joueurs différents → silence temporaire',()=>{const w=W(),bad=J(w,'Vilain'),r=[J(w,'A1'),J(w,'A2'),J(w,'A3')];
 assert.throws(()=>w.report(bad.sid,{id:bad.id}),e=>e.code==='not_found');
 r.forEach(x=>w.report(x.sid,{id:bad.id}));
 assert.equal(w.sync(bad.sid,{say:'salut'}).chatError.code,'muted');
 t+=11*60*1000;w.join({name:'Neuf',room:'wolof',consent:true});assert.ok(true)});
test('session : expiration par inactivité et départ',()=>{const w=W(),a=J(w,'Awa'),b=J(w,'Bo');
 t+=25000;assert.throws(()=>w.sync(a.sid,{}),e=>e.status===401);
 const c=J(w,'Cleo');assert.equal(w.sync(c.sid,{}).players.length,0,'les inactifs disparaissent');
 w.leave(c.sid);assert.throws(()=>w.sync(c.sid,{}),e=>e.status===401)});
test('salon plein',()=>{const w=W();for(let i=0;i<30;i++)J(w,'J'+i);assert.throws(()=>J(w,'Trop'),e=>e.code==='room_full')});
test('HTTP : parcours complet join → sync → chat → report → leave',async()=>{
 const srv=createServer({secret:'x',rate:{max:500,windowMs:60000}});await new Promise(r=>srv.listen(0,'127.0.0.1',r));const base='http://127.0.0.1:'+srv.address().port;
 const post=(p,b,sid)=>fetch(base+p,{method:'POST',headers:Object.assign({'content-type':'application/json'},sid?{authorization:'Bearer '+sid}:{}),body:JSON.stringify(b)}).then(async r=>({s:r.status,j:await r.json()}));
 const a=await post('/v1/world/join',{name:'Awa',room:'wolof',consent:true}),b=await post('/v1/world/join',{name:'Bo',room:'wolof',consent:true});
 assert.equal(a.s,200);
 await post('/v1/world/sync',{x:3,z:4,say:'Salut Bo'},a.j.sid);
 const v=await post('/v1/world/sync',{since:0},b.j.sid);assert.ok(v.j.chat.some(m=>m.text==='Salut Bo'));assert.equal(v.j.players[0].x,3);
 assert.equal((await post('/v1/world/sync',{})).s,401);
 assert.equal((await post('/v1/world/report',{id:a.j.id},b.j.sid)).s,202);
 assert.equal((await post('/v1/world/leave',{},b.j.sid)).s,200);assert.equal((await post('/v1/world/nope',{})).s,404);
 srv.close()});
